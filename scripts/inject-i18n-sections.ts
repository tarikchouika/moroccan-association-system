/** تحويل شجرة إلى نص TS بمسافة بادئة */
function treeToTs(tree: Tree, indent: string): string {
  return Object.entries(tree)
    .map(([k, v]) => {
      if (typeof v === "string") {
        return `${indent}${k}: ${JSON.stringify(v)},`;
      }
      return `${indent}${k}: {\n${treeToTs(v, indent + "  ")}\n${indent}},`;
    })
    .join("\n");
}

let failures = 0;
for (const [lang, data] of Object.entries(T)) {
  const path = `src/lib/i18n/dictionaries/${lang}.ts`;
  let src = readFileSync(path, "utf8");

  // 1) مفتاح nav.projects بعد associations داخل قسم nav
  const navRe = /(^  nav: \{\n(?:    \w+: "[^"]*",\n)*?    associations: "[^"]*",\n)/m;
  if (!navRe.test(src)) { console.error(`✗ ${lang}: لم يُعثر على nav.associations`); failures++; continue; }
  src = src.replace(navRe, `$1    projects: ${JSON.stringify(data.navProjects)},\n`);

  // 2) أقسام projects و dash قبل meta
  const metaIdx = src.indexOf("  meta: {");
  if (metaIdx === -1) { console.error(`✗ ${lang}: لم يُعثر على meta`); failures++; continue; }
  const sections =
    `  /** المشاريع المشتركة — الصفحة العمومية */\n` +
    `  projects: {\n${treeToTs(data.projects, "    ")}\n  },\n\n` +
    `  /** لوحة التحكم — الهيكل والإعدادات والمشاريع المشتركة */\n` +
    `  dash: {\n${treeToTs(data.dash, "    ")}\n  },\n\n`;
  src = src.slice(0, metaIdx) + sections + src.slice(metaIdx);

  // 3) مفتاح meta.pages.projects
  const pagesRe = /(pages: \{\n(?:      \w+: "[^"]*",\n)*?      associations: "[^"]*",\n)/;
  if (!pagesRe.test(src)) { console.error(`✗ ${lang}: لم يُعثر على meta.pages.associations`); failures++; continue; }
  src = src.replace(pagesRe, `$1      projects: ${JSON.stringify(data.metaProjects)},\n`);

  writeFileSync(path, src);
  console.log(`✓ ${lang}: حُقنت الأقسام الجديدة`);
}
process.exit(failures ? 1 : 0);
